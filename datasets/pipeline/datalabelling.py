import os
import zipfile
import yaml
from collections import Counter
from pathlib import Path

extract_dir = Path('/content/labeled_campus_yoloworld_only')
zip_path = Path('/content/drive/MyDrive/Ishara-h/labeled_campus_yoloworld_only.zip')

# 1. Extract dataset if not done yet
if not extract_dir.exists() or not any(extract_dir.iterdir()):
    print("Unzipping dataset...")
    with zipfile.ZipFile(zip_path, 'r') as zip_ref:
        zip_ref.extractall(extract_dir)

# 2. Automatically look for classes.txt or .yaml if present
class_names = {}

# Check for classes.txt (common in YOLO datasets without data.yaml)
classes_txt = list(extract_dir.rglob('classes.txt'))
yaml_files = list(extract_dir.rglob('*.yaml')) + list(extract_dir.rglob('*.yml'))

if classes_txt:
    print(f"Reading class names from: {classes_txt[0].name}")
    with open(classes_txt[0], 'r') as f:
        class_names = {i: line.strip() for i, line in enumerate(f) if line.strip()}
elif yaml_files:
    print(f"Reading class names from: {yaml_files[0].name}")
    with open(yaml_files[0], 'r') as f:
        data_config = yaml.safe_load(f)
        names = data_config.get('names', {})
        if isinstance(names, list):
            class_names = {i: name for i, name in enumerate(names)}
        elif isinstance(names, dict):
            class_names = names
else:
    # --- IF NO FILE IS FOUND, SET YOUR CLASS NAMES HERE ---
    # Put your 15 indoor navigation class names in order:
    class_names = {
        0: 'chair',
        1: 'table',
        2: 'door',
        3: 'obstacle',
        4: 'stair',
        # ... baaqi classes idhar add kar sakti ho
    }

# 3. Count instances across all label .txt files
counts = Counter()
all_txt = list(extract_dir.rglob('*.txt'))
label_files = [f for f in all_txt if f.name.lower() not in ['classes.txt', 'readme.txt', 'notes.txt']]

for label_file in label_files:
    with open(label_file, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if parts and parts[0].isdigit():
                class_id = int(parts[0])
                counts[class_id] += 1

# 4. Print clean report with Class ID, Name & Count
print(f"\nTotal Label Files Scanned: {len(label_files)}\n")
print(f"{'ID':<5} | {'Class Name':<25} | {'Instance Count':<14}")
print("-" * 50)

total_instances = 0
for class_id in sorted(counts.keys()):
    name = class_names.get(class_id, f"Unknown Class (ID {class_id})")
    count = counts[class_id]
    total_instances += count
    print(f"{class_id:<5} | {name:<25} | {count:<14}")

print("-" * 50)
print(f"Total Instances: {total_instances}")